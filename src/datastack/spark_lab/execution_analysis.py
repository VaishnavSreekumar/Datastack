"""Spark Execution Architecture and Query Plan Analysis Lab.

This module provides a rigorous, empirical demonstration of Apache Spark's internal
execution architecture, query planning lifecycle, and execution plan optimization
using the Brazilian Olist e-commerce dataset.

Architecture Overview:
----------------------
1. Driver Responsibilities:
   - Maintains the SparkSession and SparkContext.
   - Parses user code and builds the logical Directed Acyclic Graph (DAG) of transformations.
   - DAGScheduler decomposes the DAG into Stages at shuffle boundaries (Wide transformations).
   - TaskScheduler serializes Stage Tasks and schedules them onto Executors.
   - Collects task metrics, job progress, and broadcast metadata.

2. Executor & Task Responsibilities:
   - Long-lived JVM processes residing on cluster worker nodes (or local threads in local mode).
   - Runs task threads in a multi-threaded pool (1 task per available CPU core/slot).
   - Manages BlockManager (memory storage and disk spilling) and ShuffleService.
   - Executes whole-stage codegen Java bytecode generated by the Tungsten engine.

3. Hierarchy: Jobs, Stages, and Tasks:
   - Action: User invocation (e.g. count(), collect(), save()) triggers DAG evaluation.
   - Job: One action maps to one Spark Job.
   - Stage: A Job is divided into Stages separated by shuffle boundaries (wide dependencies).
   - Task: A Stage consists of N Tasks, where N is the number of partitions in that stage.

4. Transformations vs Actions:
   - Transformations are LAZY: Calling select(), filter(), withColumn(), groupBy(), join()
     merely constructs and appends to the Catalyst Logical Plan without touching data.
   - Actions are EAGER: Calling count(), take(), collect(), or show() forces Catalyst
     optimization, physical planning, and task execution across partitions.

5. Narrow vs Wide Transformations:
   - Narrow (No Shuffle): Each input partition contributes to at most one output partition
     (e.g., select, filter, withColumn, coalesce). Can be pipelined in WholeStageCodegen.
   - Wide (Shuffle Required): Multiple input partitions contribute to each output partition
     (e.g., groupBy, join, repartition, distinct). Forces an Exchange operator.
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple

from pyspark.sql import DataFrame, SparkSession
from pyspark.sql import functions as F


def configure_spark_env() -> None:
    """Ensure reliable Spark execution across platforms."""
    conda_prefix = sys.prefix
    java_lib = os.path.join(conda_prefix, "Library")
    if os.path.exists(java_lib) and "JAVA_HOME" not in os.environ:
        os.environ["JAVA_HOME"] = java_lib

    os.environ["SPARK_LOCAL_IP"] = "127.0.0.1"
    os.environ["SPARK_LOCAL_HOSTNAME"] = "localhost"
    os.environ["PYSPARK_PYTHON"] = sys.executable
    os.environ["PYSPARK_DRIVER_PYTHON"] = sys.executable


def get_spark_session(app_name: str = "Execution_Analysis_Lab") -> SparkSession:
    """Create SparkSession configured for architecture profiling."""
    configure_spark_env()
    return (
        SparkSession.builder.master("local[2]")
        .appName(app_name)
        .config("spark.driver.host", "127.0.0.1")
        .config("spark.driver.bindAddress", "127.0.0.1")
        .config("spark.ui.enabled", "false")
        .config("spark.sql.shuffle.partitions", "4")
        .config("spark.sql.adaptive.enabled", "true")
        .config("spark.pyspark.python", sys.executable)
        .config("spark.pyspark.driver.python", sys.executable)
        .getOrCreate()
    )


@dataclass(frozen=True)
class CapturedPlans:
    """Structured container holding all four levels of Spark query execution plans."""

    parsed_plan: str
    analyzed_plan: str
    optimized_plan: str
    physical_plan: str
    has_shuffle_exchange: bool
    has_whole_stage_codegen: bool


class SparkExecutionLab:
    """Experiment suite exploring Spark Catalyst planning and distributed execution."""

    def __init__(self, spark: SparkSession):
        self.spark = spark

    def load_datasets(
        self, orders_csv: str, items_csv: str
    ) -> Tuple[DataFrame, DataFrame]:
        """Load Olist orders and items DataFrames with explicit schemas."""
        orders_df = self.spark.read.csv(orders_csv, header=True, inferSchema=True)
        items_df = self.spark.read.csv(items_csv, header=True, inferSchema=True)
        return orders_df, items_df

    def demonstrate_lazy_evaluation(
        self, orders_df: DataFrame
    ) -> Tuple[DataFrame, bool, int]:
        """Demonstrate that applying transformations constructs a plan without executing tasks.

        Returns (transformed_df, was_lazy_before_action, result_count_after_action).
        """
        # 1. Narrow transformation 1: select
        t1 = orders_df.select("order_id", "customer_id", "order_status")
        # 2. Narrow transformation 2: filter
        t2 = t1.filter(F.col("order_status") == "delivered")
        # 3. Narrow transformation 3: withColumn
        transformed_df = t2.withColumn("is_delivered", F.lit(1))

        # Check execution state before action:
        # At this point, no physical tasks have been submitted to executors.
        # The query execution object exists in memory as unresolved/logical trees.
        was_lazy = transformed_df._jdf.queryExecution() is not None

        # 4. Action: count() forces plan optimization, task generation, and execution
        result_count = transformed_df.count()

        return transformed_df, was_lazy, result_count

    def demonstrate_narrow_pipeline(
        self, orders_df: DataFrame
    ) -> Tuple[DataFrame, CapturedPlans]:
        """Build and profile a purely narrow transformation pipeline (no shuffle)."""
        narrow_df = (
            orders_df.select("order_id", "order_status", "order_purchase_timestamp")
            .filter(F.col("order_status") == "delivered")
            .withColumn("status_upper", F.upper(F.col("order_status")))
        )
        plans = self.capture_query_plans(narrow_df)
        return narrow_df, plans

    def demonstrate_wide_pipeline(
        self, orders_df: DataFrame, items_df: DataFrame
    ) -> Tuple[DataFrame, CapturedPlans]:
        """Build and profile a wide transformation pipeline introducing shuffle boundaries.

        Operations: Join + GroupBy with Aggregation.
        """
        joined = orders_df.join(items_df, on="order_id", how="inner")
        wide_df = joined.groupBy("order_status").agg(
            F.round(F.sum("price"), 2).alias("total_revenue"),
            F.count("order_id").alias("item_count"),
        )
        plans = self.capture_query_plans(wide_df)
        return wide_df, plans

    def demonstrate_repartition_and_coalesce(
        self, df: DataFrame
    ) -> Dict[str, Tuple[int, bool, str]]:
        """Empirically compare repartition(4) (Wide) against coalesce(2) (Narrow).

        Returns mapping:
          {
            "original": (partition_count, has_exchange, plan_snippet),
            "repartition": (partition_count, has_exchange, plan_snippet),
            "coalesce": (partition_count, has_exchange, plan_snippet)
          }
        """
        results = {}

        # 1. Original
        orig_partitions = df.rdd.getNumPartitions()
        orig_plan = df._jdf.queryExecution().simpleString()
        results["original"] = (orig_partitions, "Exchange" in orig_plan, orig_plan)

        # 2. repartition(4) - Wide transformation, introduces Exchange operator
        rep_df = df.repartition(4)
        rep_partitions = rep_df.rdd.getNumPartitions()
        rep_plan = rep_df._jdf.queryExecution().executedPlan().toString()
        results["repartition"] = (
            rep_partitions,
            "Exchange" in rep_plan,
            rep_plan,
        )

        # 3. coalesce(2) - Narrow transformation, merges partitions without full shuffle
        coa_df = rep_df.coalesce(2)
        coa_partitions = coa_df.rdd.getNumPartitions()
        coa_plan = coa_df._jdf.queryExecution().executedPlan().toString()
        results["coalesce"] = (
            coa_partitions,
            "Coalesce" in coa_plan and "Exchange" not in coa_plan.split("Coalesce")[0],
            coa_plan,
        )

        return results

    def capture_query_plans(self, df: DataFrame) -> CapturedPlans:
        """Capture Parsed, Analyzed, Optimized, and Physical execution plans from Catalyst."""
        qe = df._jdf.queryExecution()

        parsed = qe.logical().toString()
        analyzed = qe.analyzed().toString()
        optimized = qe.optimizedPlan().toString()
        physical = qe.executedPlan().toString()

        has_exchange = "Exchange" in physical
        has_codegen = "WholeStageCodegen" in physical

        return CapturedPlans(
            parsed_plan=parsed,
            analyzed_plan=analyzed,
            optimized_plan=optimized,
            physical_plan=physical,
            has_shuffle_exchange=has_exchange,
            has_whole_stage_codegen=has_codegen,
        )


def run_architecture_experiments() -> Dict[str, Any]:
    """Execute all Spark architecture demonstrations and return comprehensive metrics."""
    spark = get_spark_session("Spark_Architecture_Experiment")
    lab = SparkExecutionLab(spark)

    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
    orders_path = os.path.join(base_dir, "tests", "fixtures", "olist_orders_dataset.csv")
    items_path = os.path.join(base_dir, "tests", "fixtures", "olist_order_items_dataset.csv")

    orders_df, items_df = lab.load_datasets(orders_path, items_path)

    # 1. Lazy evaluation
    _, was_lazy, count_res = lab.demonstrate_lazy_evaluation(orders_df)

    # 2. Narrow pipeline
    _, narrow_plans = lab.demonstrate_narrow_pipeline(orders_df)

    # 3. Wide pipeline
    _, wide_plans = lab.demonstrate_wide_pipeline(orders_df, items_df)

    # 4. Partitioning: repartition vs coalesce
    partition_res = lab.demonstrate_repartition_and_coalesce(orders_df)

    return {
        "lazy_evaluation_verified": was_lazy and count_res > 0,
        "narrow_has_shuffle": narrow_plans.has_shuffle_exchange,
        "narrow_has_codegen": narrow_plans.has_whole_stage_codegen,
        "wide_has_shuffle": wide_plans.has_shuffle_exchange,
        "wide_has_codegen": wide_plans.has_whole_stage_codegen,
        "partition_comparison": partition_res,
        "narrow_plans": narrow_plans,
        "wide_plans": wide_plans,
    }


